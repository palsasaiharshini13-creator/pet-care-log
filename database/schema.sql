-- Pet Care Log database schema for Supabase PostgreSQL
create table if not exists public.pets (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 60),
  species text not null check (species in ('Dog', 'Cat', 'Bird', 'Rabbit', 'Other')),
  breed text not null default '' check (char_length(breed) <= 60),
  birth_date date,
  weight_kg numeric(6,2) check (weight_kg is null or (weight_kg > 0 and weight_kg <= 500)),
  notes text not null default '' check (char_length(notes) <= 500),
  created_at timestamptz not null default now()
);

create table if not exists public.care_records (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  type text not null check (type in ('health', 'feeding', 'appointment', 'medication', 'grooming')),
  record_date date not null,
  title text not null check (char_length(trim(title)) between 1 and 100),
  details text not null default '' check (char_length(details) <= 1000),
  next_date date,
  created_at timestamptz not null default now()
);

create index if not exists idx_care_records_pet_id on public.care_records(pet_id);
create index if not exists idx_care_records_record_date on public.care_records(record_date desc);
create index if not exists idx_care_records_type on public.care_records(type);

-- This beginner MVP uses a server-side Supabase key, so the API server is the
-- only intended database access path. Do not expose that key in frontend code.
-- For a public deployment, add authentication, ownership columns, RLS policies,
-- and authorization checks before allowing anyone else to use the app.
alter table public.pets enable row level security;
alter table public.care_records enable row level security;
